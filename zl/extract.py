def export_records(items, output_file=DEFAULT_OUTPUT_FILE, job_type_level_2=""):
    output_path = Path(output_file)
    if output_path.exists():
        wb = load_workbook(output_path)
        ws = wb.active
        start_index = ws.max_row
    else:
        wb = Workbook()
        ws = wb.active
        ws.title = "提取结果"
        ws.append(HEADERS)
        start_index = 1

    for index, item in enumerate(items, start_index):
        record = build_record(index, item, job_type_level_2)
        ws.append([record.get(clean_header(header), "") for header in HEADERS])

    wb.save(output_path)


def extract_to_xlsx(json_string, output_file=DEFAULT_OUTPUT_FILE, job_type_level_2=""):
    items = parse_items(json_string)
    export_records(items, output_file, job_type_level_2)
    return {
        "count": len(items),
        "output_file": str(output_file),
    }


